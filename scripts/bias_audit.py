#!/usr/bin/env python
"""
Bias/Fairness Audit for ShadeSense Skin Tone Analysis

This script batch-runs the pipeline against the folder-organised dataset and
reports how its outputs (and confidence) are distributed per group.

IMPORTANT: the folder names in ai/data/raw were generated by an older colour
heuristic, NOT by people. "Agreement" below is agreement between two heuristics,
not accuracy. For real accuracy use scripts/eval.py with hand-labelled images.
"""

import csv
import os
import re
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import cv2
import numpy as np
from tqdm import tqdm

# Add project root to path
PROJECT_ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from ai.colorimetry.face_color import analyze_face_color  # noqa: E402


class BiasAudit:
    def __init__(self, image_dir: str, output_dir: str = "audit_results"):
        self.image_dir = Path(image_dir)
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)
        
        # Results storage
        self.results = []
        self.summary = {
            "total_images": 0,
            "successful": 0,
            "failed": 0,
            "by_depth": defaultdict(lambda: {"count": 0, "confidences": [], "images": []}),
            "by_undertone": defaultdict(lambda: {"count": 0, "confidences": [], "images": []}),
            "by_depth_undertone": defaultdict(lambda: {"count": 0, "confidences": [], "images": []}),
        }
        
    def load_images(self) -> List[Tuple[Path, str, str]]:
        """Load all images and extract depth/undertone from folder names."""
        images = []
        image_extensions = {'.jpg', '.jpeg', '.png', '.bmp', '.tiff'}
        
        # Walk through all subdirectories
        for folder_path in self.image_dir.iterdir():
            if not folder_path.is_dir():
                continue
            
            # Parse folder name: e.g., "light_cool" -> depth="light", undertone="cool"
            folder_name = folder_path.name
            match = re.match(r'^(light|medium|deep)_(cool|neutral|olive|warm)$', folder_name)
            if not match:
                print(f"⚠️ Skipping unrecognized folder: {folder_name}")
                continue
            
            depth, undertone = match.groups()
            
            # Find images in this folder
            for ext in image_extensions:
                for img_path in folder_path.glob(f"*{ext}"):
                    images.append((img_path, depth, undertone))
                for img_path in folder_path.glob(f"*{ext.upper()}"):
                    images.append((img_path, depth, undertone))
        
        return sorted(images, key=lambda x: (x[1], x[2], x[0].name))
    
    def analyze_image(self, image_path: Path, expected_depth: str, expected_undertone: str) -> Optional[Dict]:
        """Run the pipeline on a single image."""
        try:
            # Read image
            img = cv2.imread(str(image_path))
            if img is None:
                return None
            
            # Run analysis
            result = analyze_face_color(img, use_haar_fallback=True)
            
            # Extract key metrics
            return {
                "image": image_path.name,
                "folder": image_path.parent.name,
                "expected_depth": expected_depth,
                "expected_undertone": expected_undertone,
                "detected_depth": result.get("depth", "unknown"),
                "detected_undertone": result.get("undertone", "unknown"),
                "detected_clarity": result.get("clarity", "unknown"),
                "detected_contrast": result.get("contrast", "unknown"),
                "confidence": result.get("confidence", 0.0),
                "ita_degrees": result.get("ita_degrees", 0.0),
                "ita_bucket": result.get("ita_bucket", "unknown"),
                "L": result.get("L", 0.0),
                "a": result.get("a", 0.0),
                "b": result.get("b", 0.0),
                "depth_match": result.get("depth", "unknown") == expected_depth,
                "undertone_match": result.get("undertone", "unknown") == expected_undertone,
                "success": True
            }
        except Exception as e:
            return {
                "image": image_path.name,
                "folder": image_path.parent.name,
                "expected_depth": expected_depth,
                "expected_undertone": expected_undertone,
                "success": False,
                "error": str(e)
            }
    
    def run_audit(self):
        """Run the full audit."""
        images = self.load_images()
        
        if not images:
            print(f"❌ No images found in {self.image_dir}")
            print("   Expected folders: light_*, medium_*, deep_*")
            return
        
        print(f"🔍 Found {len(images)} images across {len(set(img[0].parent for img in images))} folders")
        print("   Running analysis...\n")
        
        for img_path, depth, undertone in tqdm(images, desc="Analyzing"):
            result = self.analyze_image(img_path, depth, undertone)
            if result:
                self.results.append(result)
                
                if result.get("success", False):
                    self.summary["successful"] += 1
                    self._update_summary(result)
                else:
                    self.summary["failed"] += 1
                    print(f"⚠️ Failed: {result.get('image')} - {result.get('error', 'Unknown error')}")
            
            self.summary["total_images"] += 1
        
        self._generate_report()
    
    def _update_summary(self, result: Dict):
        """Update summary statistics with a successful result."""
        # By depth
        depth = result.get("detected_depth", "unknown")
        self.summary["by_depth"][depth]["count"] += 1
        self.summary["by_depth"][depth]["confidences"].append(result.get("confidence", 0.0))
        self.summary["by_depth"][depth]["images"].append(result.get("image", ""))
        
        # By undertone
        undertone = result.get("detected_undertone", "unknown")
        self.summary["by_undertone"][undertone]["count"] += 1
        self.summary["by_undertone"][undertone]["confidences"].append(result.get("confidence", 0.0))
        self.summary["by_undertone"][undertone]["images"].append(result.get("image", ""))
        
        # By depth + undertone
        key = f"{result.get('expected_depth', 'unknown')}_{result.get('expected_undertone', 'unknown')}"
        self.summary["by_depth_undertone"][key]["count"] += 1
        self.summary["by_depth_undertone"][key]["confidences"].append(result.get("confidence", 0.0))
        self.summary["by_depth_undertone"][key]["images"].append(result.get("image", ""))
    
    def _calculate_stats(self, confidences: List[float]) -> Dict:
        """Calculate statistics for a list of confidence scores."""
        if not confidences:
            return {"count": 0, "avg": 0, "min": 0, "max": 0, "std": 0}
        
        conf_arr = np.array(confidences)
        return {
            "count": len(confidences),
            "avg": float(np.mean(conf_arr)),
            "min": float(np.min(conf_arr)),
            "max": float(np.max(conf_arr)),
            "std": float(np.std(conf_arr)),
            "p25": float(np.percentile(conf_arr, 25)),
            "p50": float(np.percentile(conf_arr, 50)),
            "p75": float(np.percentile(conf_arr, 75)),
        }
    
    def _generate_report(self):
        """Generate a comprehensive report."""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        
        # Detailed CSV results
        csv_path = self.output_dir / f"audit_results_{timestamp}.csv"
        with open(csv_path, 'w', newline='') as f:
            if self.results:
                # Filter out success field for CSV
                fieldnames = [k for k in self.results[0].keys() if k not in ['success', 'error']]
                writer = csv.DictWriter(f, fieldnames=fieldnames)
                writer.writeheader()
                for row in self.results:
                    writer.writerow({k: v for k, v in row.items() if k in fieldnames})
        
        # Summary report
        report_path = self.output_dir / f"audit_report_{timestamp}.txt"
        with open(report_path, 'w') as f:
            f.write("=" * 80 + "\n")
            f.write("SHADESENSE BIAS/FAIRNESS AUDIT REPORT\n")
            f.write("=" * 80 + "\n\n")
            
            f.write(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
            f.write(f"Images analyzed: {self.summary['total_images']}\n")
            f.write(f"Successful: {self.summary['successful']}\n")
            f.write(f"Failed: {self.summary['failed']}\n")
            f.write(f"Success rate: {self.summary['successful']/max(1,self.summary['total_images'])*100:.1f}%\n\n")
            
            # Agreement with heuristic folder labels
            f.write("=" * 80 + "\n")
            f.write("AGREEMENT WITH FOLDER LABELS (heuristic labels, NOT ground truth)\n")
            f.write("=" * 80 + "\n")
            
            depth_correct = sum(1 for r in self.results if r.get("success", False) and r.get("depth_match", False))
            undertone_correct = sum(1 for r in self.results if r.get("success", False) and r.get("undertone_match", False))
            
            f.write(f"\nDepth agreement with folder labels: {depth_correct}/{self.summary['successful']} ({depth_correct/max(1,self.summary['successful'])*100:.1f}%)\n")
            f.write(f"Undertone agreement with folder labels: {undertone_correct}/{self.summary['successful']} ({undertone_correct/max(1,self.summary['successful'])*100:.1f}%)\n")
            
            # By Depth
            f.write("\n" + "=" * 80 + "\n")
            f.write("CONFIDENCE BY SKIN TONE DEPTH\n")
            f.write("=" * 80 + "\n")
            
            for depth in ["light", "medium", "deep"]:
                data = self.summary["by_depth"].get(depth, {"count": 0, "confidences": []})
                stats = self._calculate_stats(data["confidences"])
                f.write(f"\n{depth.upper()}:\n")
                f.write(f"  Count: {stats['count']}\n")
                f.write(f"  Avg Confidence: {stats['avg']:.3f}\n")
                f.write(f"  Min: {stats['min']:.3f}, Max: {stats['max']:.3f}\n")
                f.write(f"  Std Dev: {stats['std']:.3f}\n")
            
            # By Undertone
            f.write("\n" + "=" * 80 + "\n")
            f.write("CONFIDENCE BY UNDERTONE\n")
            f.write("=" * 80 + "\n")
            
            for undertone in ["cool", "neutral", "olive", "warm"]:
                data = self.summary["by_undertone"].get(undertone, {"count": 0, "confidences": []})
                stats = self._calculate_stats(data["confidences"])
                f.write(f"\n{undertone.upper()}:\n")
                f.write(f"  Count: {stats['count']}\n")
                f.write(f"  Avg Confidence: {stats['avg']:.3f}\n")
                f.write(f"  Min: {stats['min']:.3f}, Max: {stats['max']:.3f}\n")
                f.write(f"  Std Dev: {stats['std']:.3f}\n")
            
            # By Depth + Undertone (detailed)
            f.write("\n" + "=" * 80 + "\n")
            f.write("CONFIDENCE BY DEPTH + UNDERTONE\n")
            f.write("=" * 80 + "\n")
            
            for key, data in sorted(self.summary["by_depth_undertone"].items()):
                stats = self._calculate_stats(data["confidences"])
                f.write(f"\n{key.upper()}:\n")
                f.write(f"  Count: {stats['count']}\n")
                f.write(f"  Avg Confidence: {stats['avg']:.3f}\n")
                f.write(f"  Min: {stats['min']:.3f}, Max: {stats['max']:.3f}\n")
            
            # Bias Detection
            f.write("\n" + "=" * 80 + "\n")
            f.write("BIAS DETECTION SUMMARY\n")
            f.write("=" * 80 + "\n")
            
            # Check depth bias
            depth_avgs = {}
            for depth in ["light", "medium", "deep"]:
                data = self.summary["by_depth"].get(depth, {"count": 0, "confidences": []})
                if data["confidences"]:
                    depth_avgs[depth] = np.mean(data["confidences"])
            
            if len(depth_avgs) >= 2:
                min_depth = min(depth_avgs, key=depth_avgs.get)
                max_depth = max(depth_avgs, key=depth_avgs.get)
                diff = depth_avgs[max_depth] - depth_avgs[min_depth]
                
                f.write("\n📊 Confidence by Depth:\n")
                for d, avg in sorted(depth_avgs.items()):
                    f.write(f"   {d}: {avg:.3f}\n")
                
                if diff > 0.10:
                    f.write("\n⚠️ POTENTIAL BIAS DETECTED:\n")
                    f.write(f"   Confidence gap between {min_depth} and {max_depth}: {diff:.3f}\n")
                    f.write(f"   {min_depth} avg: {depth_avgs[min_depth]:.3f}\n")
                    f.write(f"   {max_depth} avg: {depth_avgs[max_depth]:.3f}\n")
                    f.write("   Threshold: 0.10 (gap > 0.1 suggests bias)\n")
                else:
                    f.write("\n✅ No significant bias detected by depth.\n")
                    f.write(f"   Confidence range: {min(depth_avgs.values()):.3f} - {max(depth_avgs.values()):.3f}\n")
                    f.write(f"   Gap: {diff:.3f} (threshold: 0.10)\n")
            
            # Check undertone bias
            undertone_avgs = {}
            for undertone in ["cool", "neutral", "olive", "warm"]:
                data = self.summary["by_undertone"].get(undertone, {"count": 0, "confidences": []})
                if data["confidences"]:
                    undertone_avgs[undertone] = np.mean(data["confidences"])
            
            if len(undertone_avgs) >= 2:
                min_ut = min(undertone_avgs, key=undertone_avgs.get)
                max_ut = max(undertone_avgs, key=undertone_avgs.get)
                diff_ut = undertone_avgs[max_ut] - undertone_avgs[min_ut]
                
                f.write("\n📊 Confidence by Undertone:\n")
                for ut, avg in sorted(undertone_avgs.items()):
                    f.write(f"   {ut}: {avg:.3f}\n")
                
                if diff_ut > 0.10:
                    f.write("\n⚠️ POTENTIAL BIAS DETECTED by undertone:\n")
                    f.write(f"   Confidence gap between {min_ut} and {max_ut}: {diff_ut:.3f}\n")
                else:
                    f.write("\n✅ No significant bias detected by undertone.\n")
                    f.write(f"   Gap: {diff_ut:.3f} (threshold: 0.10)\n")
        
        print("\n✅ Audit complete!")
        print(f"   📊 CSV results: {csv_path}")
        print(f"   📄 Report: {report_path}")
        
        # Print quick summary
        self._print_summary()
    
    def _print_summary(self):
        """Print a quick summary to console."""
        print("\n" + "=" * 60)
        print("AUDIT SUMMARY")
        print("=" * 60)
        
        print(f"\nTotal images: {self.summary['total_images']}")
        print(f"Successful: {self.summary['successful']}")
        print(f"Failed: {self.summary['failed']}")
        print(f"Success rate: {self.summary['successful']/max(1,self.summary['total_images'])*100:.1f}%")
        
        # Agreement with heuristic folder labels
        depth_correct = sum(1 for r in self.results if r.get("success", False) and r.get("depth_match", False))
        undertone_correct = sum(1 for r in self.results if r.get("success", False) and r.get("undertone_match", False))
        
        print("\n📊 Agreement with heuristic folder labels (not accuracy):")
        print(f"   Depth: {depth_correct}/{self.summary['successful']} ({depth_correct/max(1,self.summary['successful'])*100:.1f}%)")
        print(f"   Undertone: {undertone_correct}/{self.summary['successful']} ({undertone_correct/max(1,self.summary['successful'])*100:.1f}%)")
        
        print("\n📊 Confidence by Depth:")
        for depth in ["light", "medium", "deep"]:
            data = self.summary["by_depth"].get(depth, {"count": 0, "confidences": []})
            stats = self._calculate_stats(data["confidences"])
            print(f"   {depth}: {stats['avg']:.3f} (n={stats['count']})")


def main():
    import argparse
    
    parser = argparse.ArgumentParser(description="Bias/Fairness Audit for ShadeSense")
    parser.add_argument("image_dir", 
                       default="ai/data/raw",
                       nargs='?',
                       help="Directory containing test images (default: ai/data/raw)")
    parser.add_argument("--output", "-o", default="audit_results", 
                       help="Output directory for results")
    
    args = parser.parse_args()
    
    # If no argument provided, use default
    if not args.image_dir:
        args.image_dir = "ai/data/raw"
    
    if not os.path.exists(args.image_dir):
        print(f"❌ Directory not found: {args.image_dir}")
        print("   Try: python scripts/bias_audit.py ai/data/raw")
        sys.exit(1)
    
    audit = BiasAudit(args.image_dir, args.output)
    audit.run_audit()


if __name__ == "__main__":
    main()